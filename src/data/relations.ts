export function relationshipsFor(slug: string) {
  return knowledgeRelations.filter(r => r.source === slug || r.target === slug).map(r => ({
    ...r, incoming: r.target === slug, neighbor: r.source === slug ? r.target : r.source,
    label: r.source === slug ? relationTypes[r.type].outgoing : relationTypes[r.type].incoming,
  }));
}
